        public static string Get(string language, string key)
        {
            if (string.IsNullOrWhiteSpace(key))
                return string.Empty;
            if (!Values.TryGetValue(language ?? "en", out var map))
                map = Values["en"];
            if (map.TryGetValue(key, out var value))
